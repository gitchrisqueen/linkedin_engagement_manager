"""Pins `scripts/demo_video_links.py` (issue #2379): the three demo videos' description links.

They are generated by `campaign_for_tutorial` + `signup_url`, never spelled by hand.

The landing host is patched to a fixed owned URL so the pinned strings do not depend on the
environment the suite runs in.
"""

import ast
import importlib.util
import pathlib
from urllib.parse import parse_qs, urlparse

import pytest

from cqc_lem.utilities.marketing import attribution

pytestmark = pytest.mark.unit

_SCRIPT = pathlib.Path("scripts/demo_video_links.py")
_SEED = pathlib.Path("scripts/seed_demo_account.py")
_LANDING = "https://lem.example.com/"

EXPECTED = {
    "demo1": ("https://lem.example.com/?utm_source=youtube&utm_medium=video"
              "&utm_campaign=tutorial-demo1&utm_content=video-description"),
    "demo2": ("https://lem.example.com/?utm_source=youtube&utm_medium=video"
              "&utm_campaign=tutorial-demo2&utm_content=video-description"),
    "demo3": ("https://lem.example.com/?utm_source=youtube&utm_medium=video"
              "&utm_campaign=tutorial-demo3&utm_content=video-description"),
}


@pytest.fixture
def tool(monkeypatch):
    """Load the script with its process-wide telemetry mute undone at teardown."""
    monkeypatch.setenv("LEM_TELEMETRY_MUTED", "1")
    spec = importlib.util.spec_from_file_location("demo_video_links", _SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def landing(monkeypatch):
    monkeypatch.setattr(attribution, "BRAND_SIGNUP_URL", _LANDING)
    monkeypatch.setattr(attribution, "PUBLIC_BASE_URL", "")
    monkeypatch.setattr(attribution, "MARKETING_OWNED_DOMAINS", "")


def test_the_three_videos_are_the_three_seed_scenes(tool):
    """The demo videos ARE the recordings of the seed's scenes.

    Drift between the two would tag a video nobody recorded. Read off the seed's source so no
    database import is needed.
    """
    tree = ast.parse(_SEED.read_text(encoding="utf-8"))
    scenes = next(
        ast.literal_eval(node.value) for node in tree.body
        if isinstance(node, ast.Assign)
        and any(isinstance(t, ast.Name) and t.id == "SCENES" for t in node.targets)
    )
    assert tool.DEMO_VIDEOS == scenes == ("demo1", "demo2", "demo3")


def test_each_link_is_pinned(tool, landing):
    assert tool.demo_video_links() == EXPECTED


@pytest.mark.parametrize("scene", ["demo1", "demo2", "demo3"])
def test_each_link_carries_the_tutorial_utms(tool, landing, scene):
    url = tool.demo_video_links()[scene]
    parsed = urlparse(url)
    params = {key: values[0] for key, values in parse_qs(parsed.query).items()}

    assert f"{parsed.scheme}://{parsed.netloc}{parsed.path}" == _LANDING
    assert params == {
        "utm_source": "youtube",
        "utm_medium": "video",
        "utm_campaign": f"tutorial-{scene}",
        "utm_content": "video-description",
    }
    assert params["utm_campaign"] == attribution.campaign_for_tutorial(scene)


def test_a_hand_tagged_landing_keeps_its_own_utms(tool, monkeypatch):
    """Existing UTMs are never overwritten — only the missing ones are filled in."""
    monkeypatch.setattr(attribution, "BRAND_SIGNUP_URL",
                        "https://lem.example.com/trial?utm_source=partner")
    monkeypatch.setattr(attribution, "PUBLIC_BASE_URL", "")

    params = parse_qs(urlparse(tool.demo_video_links()["demo1"]).query)

    assert params["utm_source"] == ["partner"]
    assert params["utm_campaign"] == ["tutorial-demo1"]


def test_main_prints_one_line_per_video(tool, landing, capsys):
    assert tool.main([]) == tool.EXIT_OK

    lines = capsys.readouterr().out.splitlines()
    assert lines == [f"{scene}\t{url}" for scene, url in EXPECTED.items()]


def test_main_refuses_without_a_landing_page(tool, monkeypatch, capsys):
    monkeypatch.setattr(attribution, "BRAND_SIGNUP_URL", "")
    monkeypatch.setattr(attribution, "PUBLIC_BASE_URL", "")

    assert tool.main([]) == tool.EXIT_NO_LANDING

    captured = capsys.readouterr()
    assert captured.out == ""
    assert "BRAND_SIGNUP_URL" in captured.err
